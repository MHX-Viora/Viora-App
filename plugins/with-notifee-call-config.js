const {
  withAppBuildGradle,
  withAndroidManifest,
  withDangerousMod,
  withProjectBuildGradle,
} = require("@expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

const NOTIFEE_REPOSITORY =
  'maven { url "$rootDir/../node_modules/@notifee/react-native/android/libs" }';
const NOTIFEE_MARKER = "// @generated by with-notifee-call-config";
const FIREBASE_MESSAGING_DEPENDENCIES = `    implementation(platform("com.google.firebase:firebase-bom:34.15.0"))
    implementation("com.google.firebase:firebase-messaging")`;
const NATIVE_CALL_SOURCES = [
  "IncomingCallActionReceiver.kt",
  "IncomingCallActivity.kt",
  "IncomingCallMessagingReceiver.kt",
  "IncomingCallNotificationPresenter.kt",
  "IncomingCallPayload.kt",
  "IncomingCallSettingsModule.kt",
  "IncomingCallSettingsPackage.kt",
];

const replaceRequired = (contents, search, replacement, label) => {
  if (!contents.includes(search)) {
    throw new Error(`Cannot patch ${label}: expected Expo template anchor was not found.`);
  }
  return contents.replace(search, replacement);
};

const patchMainActivity = (contents) => {
  if (contents.includes("cancelIncomingCallNotification(intent)")) return contents;
  const imports = `import android.app.KeyguardManager
import android.content.Intent
import com.ankt.app.calls.IncomingCallNotificationPresenter
`;
  const lifecycle = `    updateCallLockScreenVisibility(intent)
    super.onCreate(null)
    cancelIncomingCallNotification(intent)`;
  const helpers = `  override fun onNewIntent(intent: Intent) {
    super.onNewIntent(intent)
    setIntent(intent)
    updateCallLockScreenVisibility(intent)
    cancelIncomingCallNotification(intent)
  }

  private fun cancelIncomingCallNotification(intent: Intent?) {
    if (!isCallIntent(intent)) return
    val callId = intent?.data?.pathSegments?.firstOrNull().orEmpty()
    if (callId.isNotBlank()) IncomingCallNotificationPresenter.cancel(this, callId)
  }

  private fun updateCallLockScreenVisibility(intent: Intent?) {
    val showCallOverKeyguard = isCallIntent(intent)
    setShowWhenLocked(showCallOverKeyguard)
    setTurnScreenOn(showCallOverKeyguard)
    if (!showCallOverKeyguard) return

    val keyguardManager = getSystemService(KeyguardManager::class.java)
    if (keyguardManager.isKeyguardLocked && !keyguardManager.isDeviceSecure) {
      keyguardManager.requestDismissKeyguard(this, null)
    }
  }

  private fun isCallIntent(intent: Intent?): Boolean {
    val uri = intent?.data ?: return false
    return uri.scheme == "viora" && (uri.host == "call" || uri.host == "group-call")
  }

`;
  let patched = replaceRequired(
    contents,
    "import android.os.Bundle\n",
    `import android.os.Bundle\n${imports}`,
    "MainActivity imports",
  );
  patched = replaceRequired(
    patched,
    "    super.onCreate(null)",
    lifecycle,
    "MainActivity onCreate",
  );
  return replaceRequired(
    patched,
    "  override fun getMainComponentName()",
    `${helpers}  override fun getMainComponentName()`,
    "MainActivity helpers",
  );
};

const patchMainApplication = (contents) => {
  if (contents.includes("add(IncomingCallSettingsPackage())")) return contents;
  let patched = replaceRequired(
    contents,
    "import com.facebook.react.PackageList\n",
    "import com.facebook.react.PackageList\nimport com.ankt.app.calls.IncomingCallSettingsPackage\n",
    "MainApplication imports",
  );
  return replaceRequired(
    patched,
    "              // add(MyReactNativePackage())",
    "              // add(MyReactNativePackage())\n              add(IncomingCallSettingsPackage())",
    "MainApplication packages",
  );
};

const blockOverlayPermission = (contents) =>
  contents.replace(
    '<uses-permission android:name="android.permission.SYSTEM_ALERT_WINDOW"/>',
    '<uses-permission android:name="android.permission.SYSTEM_ALERT_WINDOW" tools:node="remove"/>',
  );

const withNativeCallSources = (config) =>
  withDangerousMod(config, ["android", (modConfig) => {
    const sourceRoot = path.join(modConfig.modRequest.projectRoot, "plugins", "android-call-sources");
    const javaRoot = path.join(
      modConfig.modRequest.platformProjectRoot,
      "app", "src", "main", "java", "com", "ankt", "app",
    );
    const callRoot = path.join(javaRoot, "calls");
    fs.mkdirSync(callRoot, { recursive: true });
    for (const fileName of NATIVE_CALL_SOURCES) {
      fs.copyFileSync(path.join(sourceRoot, fileName), path.join(callRoot, fileName));
    }
    const mainActivityPath = path.join(javaRoot, "MainActivity.kt");
    fs.writeFileSync(mainActivityPath, patchMainActivity(fs.readFileSync(mainActivityPath, "utf8")));
    const mainApplicationPath = path.join(javaRoot, "MainApplication.kt");
    fs.writeFileSync(
      mainApplicationPath,
      patchMainApplication(fs.readFileSync(mainApplicationPath, "utf8")),
    );
    for (const variant of ["debug", "debugOptimized"]) {
      const manifestPath = path.join(
        modConfig.modRequest.platformProjectRoot,
        "app", "src", variant, "AndroidManifest.xml",
      );
      if (fs.existsSync(manifestPath)) {
        fs.writeFileSync(
          manifestPath,
          blockOverlayPermission(fs.readFileSync(manifestPath, "utf8")),
        );
      }
    }
    return modConfig;
  }]);

const withNotifeeRepository = (config) =>
  withProjectBuildGradle(config, (projectConfig) => {
    if (!projectConfig.modResults.contents.includes(NOTIFEE_REPOSITORY)) {
      projectConfig.modResults.contents += `

${NOTIFEE_MARKER}
allprojects {
  repositories {
    ${NOTIFEE_REPOSITORY}
  }
}
`;
    }
    return projectConfig;
  });

const withFirebaseMessagingDependency = (config) =>
  withAppBuildGradle(config, (appConfig) => {
    if (!appConfig.modResults.contents.includes('implementation("com.google.firebase:firebase-messaging")')) {
      appConfig.modResults.contents = appConfig.modResults.contents.replace(
        /dependencies\s*\{/,
        `dependencies {\n${FIREBASE_MESSAGING_DEPENDENCIES}`,
      );
    }
    return appConfig;
  });

const withIncomingCallActivity = (config) =>
  withAndroidManifest(config, (manifestConfig) => {
    const application = manifestConfig.modResults.manifest.application?.[0];
    const activities = application?.activity ?? [];
    const mainActivity = activities.find((activity) =>
      activity["intent-filter"]?.some((intentFilter) =>
        intentFilter.action?.some(
          (action) => action.$?.["android:name"] === "android.intent.action.MAIN",
        ),
      ),
    );

    if (mainActivity) {
      delete mainActivity.$["android:showWhenLocked"];
      delete mainActivity.$["android:turnScreenOn"];
    }

    application.activity = activities.filter(
      (activity) => activity.$?.["android:name"] !== ".calls.IncomingCallActivity",
    );
    application.activity.push({
      $: {
        "android:name": ".calls.IncomingCallActivity",
        "android:excludeFromRecents": "true",
        "android:exported": "false",
        "android:launchMode": "singleTop",
        "android:screenOrientation": "portrait",
        "android:showWhenLocked": "true",
        "android:theme": "@style/AppTheme",
        "android:turnScreenOn": "true",
      },
    });

    const receivers = application.receiver ?? [];
    application.receiver = receivers.filter(
      (receiver) =>
        ![
          "io.invertase.firebase.messaging.ReactNativeFirebaseMessagingReceiver",
          ".calls.IncomingCallMessagingReceiver",
          ".calls.IncomingCallActionReceiver",
        ].includes(receiver.$?.["android:name"]),
    );
    application.receiver.push(
      {
        $: {
          "android:name":
            "io.invertase.firebase.messaging.ReactNativeFirebaseMessagingReceiver",
          "tools:node": "remove",
        },
      },
      {
        $: {
          "android:name": ".calls.IncomingCallMessagingReceiver",
          "android:exported": "true",
          "android:permission": "com.google.android.c2dm.permission.SEND",
        },
        "intent-filter": [
          {
            action: [
              { $: { "android:name": "com.google.android.c2dm.intent.RECEIVE" } },
            ],
          },
        ],
      },
      {
        $: {
          "android:name": ".calls.IncomingCallActionReceiver",
          "android:exported": "false",
        },
      },
    );

    return manifestConfig;
  });

module.exports = (config) =>
  withNativeCallSources(
    withIncomingCallActivity(
      withFirebaseMessagingDependency(withNotifeeRepository(config)),
    ),
  );
